func contains(haystack, needle []byte) bool {
	if len(needle) == 0 {
		return true
	}
	for i := 0; i+len(needle) <= len(haystack); i++ {
		match := true
		for j := 0; j < len(needle); j++ {
			if haystack[i+j] != needle[j] {
				match = false
				break
			}
		}
		if match {
			return true
		}
	}
	return false
}

type dummyWriter struct{}

func (d *dummyWriter) Write(p []byte) (int, error) { return len(p), nil }

// localConfig builds a config.Config with no R2 credentials — the
// factory will pick LocalStore.
func localConfig(localDir string) *config.Config {
	return &config.Config{
		LocalPDFDir: localDir,
	}
}
